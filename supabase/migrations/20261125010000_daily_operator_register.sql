-- DOWNTIME Operator on Duty: one immutable-by-default assignment per calendar date.
-- Writes are available only through the authenticated central-bank Edge Function.
create table if not exists public.downtime_daily_operator_assignments (
  duty_date date primary key,
  operator_name text not null check (length(btrim(operator_name)) between 1 and 60),
  is_locked boolean not null default true,
  assigned_by text not null,
  assigned_at timestamptz not null default now(),
  locked_by text not null,
  locked_at timestamptz not null default now(),
  updated_by text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.downtime_daily_operator_audit (
  id bigint generated by default as identity primary key,
  duty_date date not null,
  action text not null check (action in ('ASSIGNED','UNLOCKED','REASSIGNED')),
  operator_name text,
  previous_operator text,
  actor text not null,
  reason text,
  created_at timestamptz not null default now()
);

create index if not exists downtime_daily_operator_audit_date_idx
  on public.downtime_daily_operator_audit (duty_date, created_at desc);

alter table public.downtime_daily_operator_assignments enable row level security;
alter table public.downtime_daily_operator_audit enable row level security;
revoke all on public.downtime_daily_operator_assignments from public, anon, authenticated;
revoke all on public.downtime_daily_operator_audit from public, anon, authenticated;
grant all on public.downtime_daily_operator_assignments to service_role;
grant all on public.downtime_daily_operator_audit to service_role;
