-- Central-bank auth/session support tables. Additive only; no legacy data is deleted.
create table if not exists public.downtime_central_sessions (
  token_hash text primary key,
  username text not null,
  tier text not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
alter table public.downtime_central_sessions enable row level security;
revoke all on public.downtime_central_sessions from anon, authenticated;
grant all on public.downtime_central_sessions to service_role;

create table if not exists public.downtime_central_audit (
  id bigint generated by default as identity primary key,
  username text not null,
  action text not null,
  created_at timestamptz not null default now(),
  details jsonb not null default '{}'::jsonb
);
alter table public.downtime_central_audit enable row level security;
revoke all on public.downtime_central_audit from anon, authenticated;
grant all on public.downtime_central_audit to service_role;

