import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const html=read('../repair-maintenance.html'),app=read('../repair-maintenance-app.js');
const api=read('../supabase/functions/repair-maintenance-api/index.ts'),pdf=read('../supabase/functions/repair-maintenance-api/pdf.ts');
const machines=['KIVERCO_PICKING_LINE','TANNA_SHREDDER','FORKLIFT','TELEHANDLER','EXCAVATORS_360','OTHER_EQUIPMENT'];
assert.match(html,/id="reportOverlay"/);
assert.match(html,/id="reportMachineType"/);
for(const key of machines)assert.ok(html.includes('option value="'+key+'"'),'missing machinery option '+key);
assert.match(html,/id="generatePdfReport"/);
assert.match(html,/id="reportAssetId"/);
assert.match(app,/api\('export-create'/);
assert.match(app,/assetChoice==='__UNASSIGNED__'/,'PDF generation supports legacy unassigned fault records');
assert.match(app,/else if\(assetChoice\)filters\.assetId=assetChoice/,'PDF generation supports an individual machine');
assert.match(api,/action === "export-create"/);
assert.match(api,/maxRecords\s*=\s*10000/);
assert.match(api,/range\(offset,\s*offset\s*\+\s*pageSize\s*-\s*1\)/);
assert.match(pdf,/No faults or defects recorded/);
for(const field of ['fault_name','description','priority','status','created_at'])assert.ok(pdf.includes('f.'+field),'PDF missing '+field);
assert.match(pdf,/asset_name/,'PDF groups faults under registered machinery');
console.log('R&M PDF report generation regression: PASS');
