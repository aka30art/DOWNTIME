import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const html=read('../repair-maintenance.html');
const app=read('../repair-maintenance-app.js');
const api=read('../supabase/functions/repair-maintenance-api/index.ts');
const machines=['KIVERCO_PICKING_LINE','TANNA_SHREDDER','FORKLIFT','TELEHANDLER','EXCAVATORS_360','OTHER_EQUIPMENT'];
assert.match(html,/id="openReports"/,'R&M header exposes the reports icon');
assert.match(html,/id="reportOverlay"/,'reports use a dedicated screen');
assert.match(html,/id="reportMachineType"/,'reports expose a machinery filter');
assert.match(html,/option value="">ALL MACHINERY/,'all-machinery filter is available');
for(const key of machines)assert.ok(html.includes('option value="'+key+'"'),'missing report filter '+key);
assert.match(html,/id="generatePdfReport"/,'report screen exposes PDF generation');
assert.match(app,/api\('report-list'/,'client calls the report-list API');
assert.match(app,/id="reportPrintButton"/,'generated report contains its own print-to-PDF action');
assert.match(app,/access\?\.canExportRepairMaintenanceReports!==true/,'client gates report generation by permission');
const action=api.match(/if \(action === "report-list"\) \{([\s\S]*?)\n    \}\n\n    if \(action === "get"\)/)?.[1]||'';
assert.ok(action,'server exposes a dedicated report-list action');
assert.match(action,/permissions\.canExportRepairMaintenanceReports !== true/,'server independently enforces export permission');
assert.match(action,/machineTypes/,'server validates machinery filters');
assert.match(action,/if \(machineFilter\) query = query\.eq\("machine_type", machineFilter\)/,'server filters requested machinery');
assert.match(action,/\.range\(offset, offset \+ pageSize - 1\)/,'server paginates report results');
assert.match(action,/ascending: false/,'report records are ordered newest first');
assert.match(app,/MACHINES\)\.map\(item=>\(\{machine:item,records:records\.filter/,'all-machinery reports group records by machine');
assert.match(app,/safe\(fault\.description\)/,'PDF output escapes user-entered descriptions');
assert.match(app,/safe\(fault\.fault_name\)/,'PDF output escapes fault names');
console.log('R&M PDF reports regression: PASS');
