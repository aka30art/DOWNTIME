import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const html=await readFile('index.html','utf8');
assert.match(html,/id="staffRosterList" class="staff-roster-grid"/,'STAFF uses compact profile cards');
assert.match(html,/STAFF PROFILE/,'modal is a dedicated profile editor');
assert.match(html,/function staffModalOpen\(name=null\)/,'existing member and blank new-member flows share the modal');
assert.match(html,/if\(!manageStaff&&!manageAssign\)return;if\(!name&&!manageStaff\)return/,'only staff admins can create, assignment managers may open profile settings');
assert.match(html,/staffModalOpen\(\);/,'Add New Member opens a blank modal');
assert.match(html,/\$\('smName'\)\.readOnly=!isNew/,'existing names are protected to preserve historical records');
assert.match(html,/stationLocked/,'station lock state appears on roster and in profile modal');
assert.match(html,/manageAssign\?\{station:\$\('smStation'\)\.value,stationLocked:\$\('smLock'\)\.checked\}:\{\}/,'station and lock updates require assignment permission');
assert.match(html,/manageStaff\?\{onSite:\$\('smOnPlant'\)\.checked\}:\{\}/,'plant status updates require staff management permission');
assert.match(html,/signedStaffPhotoUpload\(name\)/,'original photos use central signed upload');
assert.match(html,/saveOperatorOriginalPhoto\(name,original\)/,'photo originals remain stored through the established local-preservation flow');
assert.match(html,/pendingOperatorPhotos\.modal/,'modal photo changes are staged before saving');
assert.match(html,/data\.length>48000/,'profile thumbnail size is constrained');
assert.match(html,/staffRoster\(\)\.filter\(n=>n!==name\)/,'staff removal only removes the roster/profile entry');
assert.match(html,/Historical records will be preserved/,'staff removal explicitly preserves history');
assert.doesNotMatch(html,/id="newStaffName"/,'old inline add-name input removed');
console.log('PASS: STAFF modal upgrade contract — cards, Add New Member, photo workflow, station lock, plant status and permissions');
