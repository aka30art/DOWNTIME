import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const html=read('../repair-maintenance.html');
const app=read('../repair-maintenance-app.js');
const api=read('../supabase/functions/repair-maintenance-api/index.ts');
const field=html.match(/<input id="newFaultStatus"[^>]*>/)?.[0]||'';
assert.match(field,/value="OPEN"/,'creation status is visibly OPEN');
assert.match(field,/disabled/,'creation status cannot be changed in the form');
assert.match(html,/New fault records always start as OPEN/,'the locked status has explanatory copy');
const clientCreate=app.match(/async function createFault\(event\)\{([\s\S]*?)\n  \}/)?.[1]||'';
assert.ok(clientCreate,'fault creation handler exists');
assert.match(clientCreate,/api\('create',\{[^}]*priority:\$\('newFaultPriority'\)\.value\s*\}\)/,'client sends create data without a status override');
assert.doesNotMatch(clientCreate,/newFaultStatus|status:/,'client creation flow does not read or send a mutable status');
const serverCreate=api.match(/if \(action === "create"\) \{([\s\S]*?)\n    \}\n\n    if \(action === "update"\)/)?.[1]||'';
assert.ok(serverCreate,'server create action exists');
assert.match(serverCreate,/status:\s*"OPEN"/,'server inserts every new fault as OPEN');
assert.doesNotMatch(serverCreate,/body\.status/,'server ignores attempted status overrides');
console.log('R&M fixed OPEN status regression: PASS');
