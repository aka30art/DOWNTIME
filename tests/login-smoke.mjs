import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import vm from 'node:vm';
import { chromium } from 'playwright';

const html = await readFile(resolve('index.html'), 'utf8');
const overviewHtml = await readFile(resolve('plant-overview-preview.html'), 'utf8');
[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(s=>s.trim()).forEach((s,i)=>new vm.Script(s,{filename:'inline-script-'+(i+1)+'.js'}));
const server=createServer((req,res)=>{res.writeHead(200,{'content-type':'text/html; charset=utf-8','cache-control':'no-store'});res.end(req.url?.startsWith('/plant-overview-preview.html')?overviewHtml:html)});
await new Promise((resolveListen,reject)=>{server.once('error',reject);server.listen(4173,'127.0.0.1',resolveListen)});
const browser=await chromium.launch({headless:true});
const errors=[];
try{
 const page=await browser.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2',route=>route.abort());
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('#authGate').isVisible(),true,'team gate should be shown');
 for(const d of '9999') await page.locator('[data-pinpad="teamPin"] [data-key="'+d+'"]').click();
 await page.locator('#unlockBtn').click();
 assert.match(await page.locator('#authMsg').textContent(),/Incorrect PIN/,'wrong team PIN should fail');
 for(const d of '0123') await page.locator('[data-pinpad="teamPin"] [data-key="'+d+'"]').click();
 await page.locator('#unlockBtn').click();
 await page.waitForFunction(()=>document.querySelector('#operatorGate').style.display==='grid');
 const names=['Jan','Mick','Gigi','Daz','Shayne'];
 for(const n of names) assert.equal(await page.locator('.operator-choice[data-operator="'+n+'"]').count(),1,n+' login should be available');
 assert.equal(await page.locator('.operator-choice[data-operator="Dowie"]').count(),0,'legacy Dowie login should be removed');
 assert.equal(await page.locator('.operator-choice[data-operator="Lee"]').count(),0,'legacy Lee login should be removed');
 assert.equal(await page.locator('.operator-choice[data-operator="Spectator"]').count(),1,'Spectator access should remain');
 assert.equal(await page.locator('.operator-choice').count(),6,'five operators plus Spectator should render');
 assert.equal(await page.locator('#refreshAppBtn').count(),1,'app refresh recovery control should be available');
 await page.locator('#refreshAppBtn').click();
 await page.waitForURL(/refresh=/);
 await page.waitForFunction(()=>document.querySelector('#authGate').style.display!=='none');
 for(const d of '0123') await page.locator('[data-pinpad="teamPin"] [data-key="'+d+'"]').click();
 await page.locator('#unlockBtn').click();
 await page.waitForFunction(()=>document.querySelector('#operatorGate').style.display==='grid');
 await page.locator('.operator-choice[data-operator="Jan"]').click();
 for(const d of '2666') await page.locator('[data-pinpad="operatorGatePin"] [data-key="'+d+'"]').click();
 await page.locator('#operatorContinue').click();
 await page.waitForFunction(()=>document.querySelector('#operatorGate').style.display==='none');
 assert.match(await page.locator('#dayHeading').textContent(),/OPERATOR: Jan/,'Jan login should work offline');
 await page.locator('#navSettings, .nav[data-view=settings]').first().click().catch(()=>{});
 assert.equal(await page.locator('#operatorAdminPanel').isVisible(),true,'Jan should retain admin controls');
 await page.locator('#newOperatorName').fill('Smoke Test User');
 await page.locator('#newOperatorInitialPin').fill('7777');
 await page.locator('#addOperatorBtn').click();
 assert.match(await page.locator('#operatorAdminMsg').textContent(),/User added/,'Jan can add app users');
 assert.ok((await page.evaluate(()=>localStorage.getItem('plantDowntime.operatorRoster.v1')||'')).includes('Smoke Test User'),'new user should be stored');
 assert.deepEqual(errors,[],'no browser JavaScript errors expected');
 console.log('PASS: incorrect and correct team PIN gate');
 console.log('PASS: canonical roster and Spectator availability');
 console.log('PASS: legacy operator accounts removed from roster');
 console.log('PASS: Refresh App cache-recovery control');
 console.log('PASS: Jan admin login and operator creation');
}finally{await browser.close();await new Promise(resolveClose=>server.close(resolveClose))}
